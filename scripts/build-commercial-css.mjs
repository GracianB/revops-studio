import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(fileURLToPath(new URL("../", import.meta.url)));
const full = readFileSync(path.join(root, "assets/css/main.css"), "utf8");
const startMarker = "/* Technical playground */";
const endMarker = "/* Commercial-first presentation, without changing the V40 decision engine. */";
const a = full.indexOf(startMarker), b = full.indexOf(endMarker);
if (a < 0 || b <= a || full.indexOf(startMarker, a + 1) !== -1 || full.indexOf(endMarker, b + 1) !== -1) {
  throw new Error("CSS extraction markers must exist exactly once in order");
}
const output = "/* AUTOGENERATED from main.css; run node scripts/build-commercial-css.mjs */\n" +
  full.slice(0, a) + full.slice(b);
if (process.argv.includes("--check")) {
  const existing = readFileSync(path.join(root, "assets/css/commercial.css"), "utf8");
  if (existing !== output) throw new Error("Stale commercial.css: run node scripts/build-commercial-css.mjs and commit it");
  console.log("COMMERCIAL_CSS_SYNC PASS: " + Buffer.byteLength(output) + " bytes vs " + Buffer.byteLength(full) + " source bytes");
} else {
  writeFileSync(path.join(root, "assets/css/commercial.css"), output);
  console.log("Commercial CSS regenerated: " + Buffer.byteLength(output) + " bytes");
}
